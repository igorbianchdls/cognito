CREATE FUNCTION erp.refletir_cadastro_normalizado() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE t bigint; e bigint; c erp.entidades_contatos; a erp.entidades_enderecos;
BEGIN
 t:=CASE WHEN TG_OP='DELETE' THEN OLD.tenant_id ELSE NEW.tenant_id END;
 e:=CASE WHEN TG_OP='DELETE' THEN OLD.entidade_id ELSE NEW.entidade_id END;
 IF TG_OP='UPDATE' AND OLD.entidade_id<>NEW.entidade_id THEN RAISE EXCEPTION 'Nao mover contato ou endereco entre entidades' USING ERRCODE='23514'; END IF;
 IF TG_TABLE_NAME='entidades_contatos' THEN
  SELECT * INTO c FROM erp.entidades_contatos WHERE tenant_id=t AND entidade_id=e AND ativo AND 'comercial'=ANY(finalidades)
   ORDER BY ('comercial'=ANY(principais)) DESC,id LIMIT 1;
  UPDATE erp.entidades SET email=c.email,telefone=c.telefone,celular=NULL,
   contato_cobranca_emails=ARRAY(SELECT DISTINCT email FROM erp.entidades_contatos WHERE tenant_id=t AND entidade_id=e AND ativo AND 'financeiro'=ANY(finalidades) AND nullif(btrim(email),'') IS NOT NULL),
   contato_cobranca_whatsapp=(SELECT telefone FROM erp.entidades_contatos WHERE tenant_id=t AND entidade_id=e AND ativo AND whatsapp AND 'financeiro'=ANY(finalidades) ORDER BY ('financeiro'=ANY(principais)) DESC,id LIMIT 1)
   WHERE tenant_id=t AND id=e;
 ELSE
  SELECT * INTO a FROM erp.entidades_enderecos WHERE tenant_id=t AND entidade_id=e AND ativo AND 'comercial'=ANY(finalidades)
   ORDER BY ('comercial'=ANY(principais)) DESC,id LIMIT 1;
  UPDATE erp.entidades SET logradouro=a.logradouro,numero=a.numero,complemento=a.complemento,bairro=a.bairro,cidade=a.cidade,uf=a.uf,cep=a.cep,pais=coalesce(a.pais,'Brasil') WHERE tenant_id=t AND id=e;
 END IF;
 RETURN NULL;
END $$;
