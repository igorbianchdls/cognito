-- Serializacao nao bloqueante evita validar agregados com snapshot anterior.
CREATE FUNCTION erp.travar_evolucao(p_tenant bigint) RETURNS void
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
 PERFORM erp.travar_periodo_empresa(p_tenant,false);
 IF NOT pg_try_advisory_xact_lock(172943,hashint8(p_tenant)) THEN
  RAISE EXCEPTION 'Operacao concorrente; repetir transacao inteira' USING ERRCODE='40001';
 END IF;
END $$;

CREATE FUNCTION erp.proteger_identidade_nova() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
BEGIN
 PERFORM erp.travar_evolucao(CASE WHEN TG_OP='DELETE' THEN OLD.tenant_id ELSE NEW.tenant_id END);
 IF TG_OP='UPDATE' AND (OLD.id<>NEW.id OR OLD.tenant_id<>NEW.tenant_id) THEN
  RAISE EXCEPTION 'Identidade imutavel' USING ERRCODE='23514';
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;

