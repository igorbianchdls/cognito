CREATE FUNCTION erp.preservar_requisicao_original() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  NEW.requisicao_original:=to_jsonb(NEW)-ARRAY['id','criado_em','requisicao_original'];
 ELSIF OLD.requisicao_original IS DISTINCT FROM NEW.requisicao_original THEN
  RAISE EXCEPTION 'Requisicao inicial preservada' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['adiantamentos','adiantamentos_aplicacoes','renegociacoes'] LOOP
 EXECUTE format('CREATE TRIGGER b_preservar_requisicao BEFORE INSERT OR UPDATE ON erp.%I FOR EACH ROW EXECUTE FUNCTION erp.preservar_requisicao_original()',t);
 END LOOP;
END $$;
CREATE FUNCTION erp.registrar_operacao_idempotente(p_tabela text,p_dados jsonb) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE t bigint; existente bigint; original jsonb; cols text; dados jsonb; k text;
BEGIN
 IF p_tabela NOT IN ('adiantamentos','adiantamentos_aplicacoes','renegociacoes') OR jsonb_typeof(p_dados) IS DISTINCT FROM 'object' THEN
  RAISE EXCEPTION 'Operacao invalida' USING ERRCODE='23514'; END IF;
 t:=(p_dados->>'tenant_id')::bigint;
 IF NOT coalesce(shared.has_erp_capability(t,'erp.financeiro.gerenciar'),false) THEN RAISE EXCEPTION 'Sem permissao financeira' USING ERRCODE='42501'; END IF;
 IF nullif(btrim(p_dados->>'chave_idempotencia'),'') IS NULL OR p_dados ?| ARRAY['id','criado_em','criado_por','requisicao_original'] THEN
  RAISE EXCEPTION 'Chave obrigatoria; campos internos nao aceitos' USING ERRCODE='23514'; END IF;
 PERFORM erp.travar_evolucao(t);
 dados:=p_dados||jsonb_build_object('criado_por',nullif(current_setting('app.erp_user_id',true),'')::bigint);
 FOR k IN SELECT jsonb_object_keys(dados) LOOP
  IF NOT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid=('erp.'||p_tabela)::regclass AND attname=k AND attnum>0 AND NOT attisdropped) THEN
   RAISE EXCEPTION 'Campo desconhecido' USING ERRCODE='23514'; END IF;
 END LOOP;
 EXECUTE format('SELECT id,requisicao_original FROM erp.%I WHERE tenant_id=$1 AND chave_idempotencia=$2',p_tabela) INTO existente,original USING t,p_dados->>'chave_idempotencia';
 IF existente IS NOT NULL THEN
  IF NOT original @> dados THEN RAISE EXCEPTION 'Chave reutilizada com conteudo diferente' USING ERRCODE='23514'; END IF;
  RETURN existente;
 END IF;
 SELECT string_agg(format('%I',key),',') INTO cols FROM jsonb_object_keys(dados) key;
 EXECUTE format('INSERT INTO erp.%I(%s) SELECT %s FROM jsonb_populate_record(NULL::erp.%I,$1) RETURNING id',p_tabela,cols,cols,p_tabela) INTO existente USING dados;
 RETURN existente;
END $$;
REVOKE ALL ON FUNCTION erp.preservar_requisicao_original(),erp.registrar_operacao_idempotente(text,jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION erp.registrar_operacao_idempotente(text,jsonb) TO erp_runtime;

COMMIT;
