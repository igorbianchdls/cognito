CREATE FUNCTION erp.registrar_evolucao_documento() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE j jsonb; antes jsonb; tid bigint; doc bigint; parcela bigint; pagamento bigint; lado text; autor bigint; ev text;
BEGIN
 j:=CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
 IF TG_OP<>'INSERT' THEN antes:=to_jsonb(OLD); END IF;
 tid:=(j->>'tenant_id')::bigint;
 autor:=nullif(current_setting('app.erp_user_id',true),'')::bigint;
 ev:=TG_TABLE_NAME||'.'||lower(TG_OP);
 IF TG_TABLE_NAME='contratos_vendas' OR TG_TABLE_NAME='contratos_vendas_versoes' THEN
  doc:=CASE WHEN TG_TABLE_NAME='contratos_vendas' THEN (j->>'id')::bigint ELSE (j->>'contrato_id')::bigint END;
  INSERT INTO erp.contratos_vendas_eventos(tenant_id,contrato_id,contrato_versao_id,evento,criado_por,dados)
   VALUES(tid,doc,CASE WHEN TG_TABLE_NAME='contratos_vendas_versoes' THEN (j->>'id')::bigint END,ev,autor,jsonb_build_object('antes',antes,'depois',j));
 ELSE
  IF TG_TABLE_NAME='pagamentos' THEN
   lado:=j->>'tipo'; pagamento:=(j->>'id')::bigint; parcela:=(j->>('conta_'||lado||'_parcela_id'))::bigint;
   EXECUTE format('SELECT conta_%s_id FROM erp.contas_%s_parcelas WHERE tenant_id=$1 AND id=$2',lado,lado) INTO doc USING tid,parcela;
  ELSE
   lado:=CASE WHEN TG_TABLE_NAME LIKE 'contas_receber%' THEN 'receber' ELSE 'pagar' END;
   IF TG_TABLE_NAME LIKE '%parcelas' THEN doc:=(j->>('conta_'||lado||'_id'))::bigint; parcela:=(j->>'id')::bigint;
   ELSE doc:=(j->>'id')::bigint; END IF;
  END IF;
  IF lado='receber' THEN
   INSERT INTO erp.contas_receber_eventos(tenant_id,conta_receber_id,conta_receber_parcela_id,pagamento_id,evento,criado_por,dados)
   VALUES(tid,doc,parcela,pagamento,ev,autor,jsonb_build_object('antes',antes,'depois',j));
  ELSE
   INSERT INTO erp.contas_pagar_eventos(tenant_id,conta_pagar_id,evento,criado_por,dados)
   VALUES(tid,doc,ev,autor,jsonb_build_object('antes',antes,'depois',j));
  END IF;
 END IF;
 RETURN NULL;
END $$;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['contas_receber','contas_receber_parcelas','contas_pagar','contas_pagar_parcelas','pagamentos','contratos_vendas','contratos_vendas_versoes'] LOOP
 EXECUTE format('CREATE TRIGGER registrar_evolucao AFTER INSERT OR UPDATE ON erp.%I FOR EACH ROW EXECUTE FUNCTION erp.registrar_evolucao_documento()',t);
 END LOOP;
END $$;
-- Dados antigos sao copiados apenas quando suficientes para formar um registro real.
INSERT INTO erp.entidades_contatos(tenant_id,entidade_id,nome,email,telefone,criado_por)
 SELECT tenant_id,id,nome,nullif(btrim(email),''),coalesce(nullif(btrim(telefone),''),nullif(btrim(celular),'')),criado_por FROM erp.entidades
 WHERE nullif(btrim(email),'') IS NOT NULL OR coalesce(nullif(btrim(telefone),''),nullif(btrim(celular),'')) IS NOT NULL;
INSERT INTO erp.entidades_enderecos(tenant_id,entidade_id,identificacao,logradouro,numero,complemento,bairro,cidade,uf,cep,pais,criado_por)
 SELECT tenant_id,id,'Endereco existente',logradouro,numero,complemento,bairro,cidade,uf,cep,pais,criado_por FROM erp.entidades
 WHERE nullif(btrim(logradouro),'') IS NOT NULL AND nullif(btrim(cidade),'') IS NOT NULL;

