CREATE FUNCTION erp.validar_principais_entidade() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE conflito boolean;
BEGIN
 IF array_position(NEW.finalidades,NULL) IS NOT NULL OR array_position(NEW.principais,NULL) IS NOT NULL
  OR cardinality(NEW.finalidades)<>(SELECT count(DISTINCT x) FROM unnest(NEW.finalidades) x)
  OR cardinality(NEW.principais)<>(SELECT count(DISTINCT x) FROM unnest(NEW.principais) x) THEN
  RAISE EXCEPTION 'Finalidades invalidas' USING ERRCODE='23514';
 END IF;
 EXECUTE format('SELECT EXISTS(SELECT 1 FROM erp.%I WHERE tenant_id=$1 AND entidade_id=$2 AND id<>$3 AND ativo AND principais && $4)',TG_TABLE_NAME)
 INTO conflito USING NEW.tenant_id,NEW.entidade_id,NEW.id,NEW.principais;
 IF conflito THEN RAISE EXCEPTION 'Principal ja definido para finalidade' USING ERRCODE='23514'; END IF;
 NEW.atualizado_em:=now();
 RETURN NEW;
END $$;

