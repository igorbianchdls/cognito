CREATE FUNCTION erp.validar_conversao_proposta() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE q erp.vendas;
BEGIN
 IF NEW.tipo_documento='venda' AND NEW.venda_origem_id IS NOT NULL AND (TG_OP='INSERT' OR NEW.venda_origem_id IS DISTINCT FROM OLD.venda_origem_id) THEN
  SELECT * INTO q FROM erp.vendas WHERE empresa_id=NEW.empresa_id AND id=NEW.venda_origem_id FOR SHARE;
  IF q.tipo_documento='orcamento' AND (q.excluido_em IS NOT NULL OR q.status='cancelada' OR q.situacao IN ('recusado','cancelado','convertido') OR q.validade_em<erp.hoje()) THEN
   RAISE EXCEPTION 'Orçamento encerrado ou vencido não pode gerar venda' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER validar_conversao_proposta BEFORE INSERT OR UPDATE OF venda_origem_id ON erp.vendas FOR EACH ROW EXECUTE FUNCTION erp.validar_conversao_proposta();
REVOKE ALL ON FUNCTION erp.validar_conversao_proposta() FROM PUBLIC,anon,authenticated;
