-- Single-level kits match the reservation expansion. Direct DB writes obey the same rule.
CREATE FUNCTION erp.validar_kit_simples() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE raiz bigint;
BEGIN
  PERFORM pg_advisory_xact_lock(NEW.tenant_id::int, hashtext('erp-stock-ledger'));
  SELECT produto_id INTO raiz FROM erp.kits_produtos WHERE tenant_id=NEW.tenant_id AND id=NEW.kit_id;
  IF raiz=NEW.produto_componente_id OR EXISTS(SELECT 1 FROM erp.kits_produtos WHERE tenant_id=NEW.tenant_id AND produto_id=NEW.produto_componente_id AND ativo AND excluido_em IS NULL)
    OR EXISTS(SELECT 1 FROM erp.kits_produtos_itens i JOIN erp.kits_produtos k ON k.tenant_id=i.tenant_id AND k.id=i.kit_id WHERE i.tenant_id=NEW.tenant_id AND i.produto_componente_id=raiz AND k.ativo AND k.excluido_em IS NULL) THEN
    RAISE EXCEPTION 'Kits aninhados ou circulares nao permitidos' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION erp.validar_kit_simples() FROM PUBLIC;
CREATE TRIGGER validar_kit_simples BEFORE INSERT OR UPDATE ON erp.kits_produtos_itens FOR EACH ROW EXECUTE FUNCTION erp.validar_kit_simples();

CREATE FUNCTION erp.validar_ativacao_kit_simples() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(NEW.tenant_id::int,hashtext('erp-stock-ledger'));
 IF NEW.ativo AND NEW.excluido_em IS NULL AND (
   EXISTS(SELECT 1 FROM erp.kits_produtos_itens i JOIN erp.kits_produtos k ON k.tenant_id=i.tenant_id AND k.id=i.kit_id WHERE i.tenant_id=NEW.tenant_id AND i.produto_componente_id=NEW.produto_id AND k.ativo AND k.excluido_em IS NULL)
   OR EXISTS(SELECT 1 FROM erp.kits_produtos_itens i JOIN erp.kits_produtos k ON k.tenant_id=i.tenant_id AND k.produto_id=i.produto_componente_id WHERE i.tenant_id=NEW.tenant_id AND i.kit_id=NEW.id AND k.ativo AND k.excluido_em IS NULL)) THEN
   RAISE EXCEPTION 'Kits aninhados ou circulares nao permitidos' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION erp.validar_ativacao_kit_simples() FROM PUBLIC;
CREATE TRIGGER validar_ativacao_kit_simples BEFORE INSERT OR UPDATE ON erp.kits_produtos FOR EACH ROW EXECUTE FUNCTION erp.validar_ativacao_kit_simples();

CREATE OR REPLACE VIEW erp.vw_giro_estoque WITH (security_invoker=true) AS
SELECT p.tenant_id,p.produto_id,p.produto,p.local_estoque_id,p.local_estoque,p.quantidade_fisica,
 COALESCE(sum(abs(m.quantidade)) FILTER(WHERE m.quantidade<0 AND m.origem_tipo='venda' AND m.ocorrido_em>=now()-interval '90 days'),0) AS saidas_90_dias,
 CASE WHEN p.quantidade_fisica>0 THEN COALESCE(sum(abs(m.quantidade)) FILTER(WHERE m.quantidade<0 AND m.origem_tipo='venda' AND m.ocorrido_em>=now()-interval '90 days'),0)/p.quantidade_fisica ELSE 0 END AS giro_90_dias
FROM erp.vw_posicao_estoque p LEFT JOIN erp.movimentacoes_estoque m ON m.tenant_id=p.tenant_id AND m.produto_id=p.produto_id AND m.local_estoque_id=p.local_estoque_id
GROUP BY p.tenant_id,p.produto_id,p.produto,p.local_estoque_id,p.local_estoque,p.quantidade_fisica;

CREATE FUNCTION erp.travar_ledger_estoque() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$
DECLARE linha jsonb := CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
BEGIN
 PERFORM pg_advisory_xact_lock((linha->>'tenant_id')::int,hashtext('erp-stock-ledger'));
 IF TG_OP='UPDATE' AND TG_TABLE_NAME IN ('saldos_estoque','reservas_estoque') THEN
   IF ROW(OLD.tenant_id,OLD.produto_id,OLD.local_estoque_id) IS DISTINCT FROM ROW(NEW.tenant_id,NEW.produto_id,NEW.local_estoque_id) THEN
     RAISE EXCEPTION 'Vinculo de estoque imutavel' USING ERRCODE='23514';
   END IF;
 END IF;
 RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
-- This trigger runs before the existing period check. Closures use the same lock.
