CREATE FUNCTION erp.validar_saldo_estoque_final() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE
  saldo erp.saldos_estoque%ROWTYPE;
  movimentos numeric;
  reservas numeric;
  ultimo erp.movimentacoes_estoque%ROWTYPE;
  negativo boolean;
  linha jsonb := CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
BEGIN
  SELECT * INTO saldo FROM erp.saldos_estoque WHERE tenant_id=(linha->>'tenant_id')::bigint
    AND produto_id=(linha->>'produto_id')::bigint AND local_estoque_id=(linha->>'local_estoque_id')::bigint;
  IF NOT FOUND THEN RAISE EXCEPTION 'Saldo de estoque ausente' USING ERRCODE='23514'; END IF;
  SELECT permite_estoque_negativo INTO negativo FROM erp.produtos WHERE tenant_id=saldo.tenant_id AND id=saldo.produto_id;
  SELECT COALESCE(sum(quantidade),0) INTO movimentos FROM erp.movimentacoes_estoque WHERE tenant_id=saldo.tenant_id AND produto_id=saldo.produto_id AND local_estoque_id=saldo.local_estoque_id;
  SELECT COALESCE(sum(quantidade-quantidade_atendida),0) INTO reservas FROM erp.reservas_estoque WHERE tenant_id=saldo.tenant_id AND produto_id=saldo.produto_id AND local_estoque_id=saldo.local_estoque_id AND status='ativa';
  SELECT * INTO ultimo FROM erp.movimentacoes_estoque WHERE tenant_id=saldo.tenant_id AND produto_id=saldo.produto_id AND local_estoque_id=saldo.local_estoque_id ORDER BY id DESC LIMIT 1;
  IF saldo.quantidade_fisica <> movimentos OR saldo.quantidade_reservada <> reservas
    OR (NOT negativo AND saldo.quantidade_fisica < saldo.quantidade_reservada)
    OR saldo.quantidade_fisica::text IN ('NaN','Infinity','-Infinity')
    OR saldo.custo_medio::text IN ('NaN','Infinity','-Infinity')
    OR (ultimo.id IS NOT NULL AND (ultimo.saldo_apos <> saldo.quantidade_fisica OR ultimo.custo_medio_apos <> saldo.custo_medio)) THEN
    RAISE EXCEPTION 'Saldo, movimentos ou reservas de estoque inconsistentes' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION erp.validar_saldo_estoque_final() FROM PUBLIC;
CREATE CONSTRAINT TRIGGER conferir_saldo_estoque AFTER INSERT OR UPDATE OR DELETE ON erp.saldos_estoque
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION erp.validar_saldo_estoque_final();
CREATE CONSTRAINT TRIGGER conferir_movimento_estoque AFTER INSERT ON erp.movimentacoes_estoque
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION erp.validar_saldo_estoque_final();
CREATE CONSTRAINT TRIGGER conferir_reserva_estoque AFTER INSERT OR UPDATE OR DELETE ON erp.reservas_estoque
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION erp.validar_saldo_estoque_final();

