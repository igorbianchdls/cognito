  FOR c IN SELECT conname FROM pg_constraint WHERE conrelid = 'erp.pagamentos'::regclass AND contype = 'c'
    AND pg_get_constraintdef(oid) LIKE '%origem%' AND pg_get_constraintdef(oid) LIKE '%conciliacao%' LOOP
