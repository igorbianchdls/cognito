BEGIN;

-- Fase 1.5 — devolução de venda: itens devolvidos voltam ao estoque e o valor é tratado de uma das três formas:
--   abater   → baixa sem dinheiro (desconto = valor) nas parcelas em aberto da venda;
--   credito  → saldo de crédito do cliente, usado depois como baixa sem dinheiro em outra parcela dele;
--   reembolso→ conta a pagar ao cliente.
-- Nenhuma das três cria entrada ou saída de caixa fictícia: baixas de abatimento e de uso de crédito têm valor
-- líquido zero, então fluxo de caixa e resultado por caixa não mudam.

CREATE TABLE erp.devolucoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id bigint NOT NULL REFERENCES shared.empresas(id) ON DELETE RESTRICT,
  venda_id bigint NOT NULL,
  cliente_id bigint NOT NULL,
  numero text NOT NULL CHECK (btrim(numero) <> ''),
  data_devolucao date NOT NULL DEFAULT erp.hoje(),
  motivo text NOT NULL CHECK (btrim(motivo) <> ''),
  tratamento text NOT NULL CHECK (tratamento IN ('abater', 'credito', 'reembolso')),
  valor_total numeric(18,2) NOT NULL CHECK (valor_total > 0),
  valor_credito numeric(18,2) NOT NULL DEFAULT 0 CHECK (valor_credito >= 0 AND valor_credito <= valor_total),
  conta_pagar_id bigint,
  documento_estoque_id bigint,
  chave_idempotencia text NOT NULL CHECK (btrim(chave_idempotencia) <> ''),
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  criado_por bigint REFERENCES shared.usuarios(id) ON DELETE SET NULL,
  atualizado_por bigint REFERENCES shared.usuarios(id) ON DELETE SET NULL,
  UNIQUE (empresa_id, id),
  UNIQUE (empresa_id, numero),
  UNIQUE (empresa_id, chave_idempotencia),
  FOREIGN KEY (empresa_id, venda_id) REFERENCES erp.vendas(empresa_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (empresa_id, cliente_id) REFERENCES erp.entidades(empresa_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (empresa_id, conta_pagar_id) REFERENCES erp.contas_pagar(empresa_id, id) ON DELETE RESTRICT,
  FOREIGN KEY (empresa_id, documento_estoque_id) REFERENCES erp.documentos_estoque(empresa_id, id) ON DELETE RESTRICT,
  CHECK ((tratamento = 'credito') = (valor_credito > 0)),
  CHECK ((tratamento = 'reembolso') = (conta_pagar_id IS NOT NULL))
);
COMMENT ON TABLE erp.devolucoes IS 'Devoluções de venda (produto devolvido ou serviço desfeito) e o tratamento financeiro escolhido.';
CREATE INDEX devolucoes_venda_idx ON erp.devolucoes(empresa_id, venda_id);
CREATE INDEX devolucoes_cliente_idx ON erp.devolucoes(empresa_id, cliente_id);

CREATE TABLE erp.devolucoes_itens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id bigint NOT NULL REFERENCES shared.empresas(id) ON DELETE RESTRICT,
  devolucao_id bigint NOT NULL,
  venda_item_id bigint NOT NULL,
  quantidade numeric(18,4) NOT NULL CHECK (quantidade > 0),
  valor numeric(18,2) NOT NULL CHECK (valor >= 0),
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (empresa_id, id),
  UNIQUE (empresa_id, devolucao_id, venda_item_id),
  FOREIGN KEY (empresa_id, devolucao_id) REFERENCES erp.devolucoes(empresa_id, id) ON DELETE CASCADE,
  FOREIGN KEY (empresa_id, venda_item_id) REFERENCES erp.vendas_itens(empresa_id, id) ON DELETE RESTRICT
);
CREATE INDEX devolucoes_itens_venda_item_idx ON erp.devolucoes_itens(empresa_id, venda_item_id);

-- Baixas ligadas à devolução: abatimento (origem devolucao) e uso de crédito (origem credito_cliente).
ALTER TABLE erp.pagamentos ADD COLUMN devolucao_id bigint;
ALTER TABLE erp.pagamentos ADD CONSTRAINT pagamentos_devolucao_fk FOREIGN KEY (empresa_id, devolucao_id) REFERENCES erp.devolucoes(empresa_id, id) ON DELETE RESTRICT;
CREATE INDEX pagamentos_devolucao_idx ON erp.pagamentos(empresa_id, devolucao_id) WHERE devolucao_id IS NOT NULL;
DO $origem$
