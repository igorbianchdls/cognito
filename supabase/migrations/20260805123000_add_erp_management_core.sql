    WHEN CURRENT_DATE - parcelas.data_vencimento <= 30 THEN '1_30'
    WHEN CURRENT_DATE - parcelas.data_vencimento <= 60 THEN '31_60'
    WHEN CURRENT_DATE - parcelas.data_vencimento <= 90 THEN '61_90' ELSE 'mais_90' END AS faixa
FROM erp.contas_pagar_parcelas AS parcelas
JOIN erp.contas_pagar AS contas ON contas.tenant_id = parcelas.tenant_id AND contas.id = parcelas.conta_pagar_id
JOIN erp.entidades ON entidades.tenant_id = contas.tenant_id AND entidades.id = contas.fornecedor_id
WHERE parcelas.excluido_em IS NULL AND parcelas.status IN ('aberto', 'parcial', 'vencido');

CREATE OR REPLACE VIEW erp.vw_giro_estoque
WITH (security_invoker = true)
AS
SELECT posicao.tenant_id, posicao.produto_id, posicao.produto,
  posicao.local_estoque_id, posicao.local_estoque, posicao.quantidade_fisica,
  COALESCE(sum(abs(movimentos.quantidade)) FILTER (WHERE movimentos.quantidade < 0 AND movimentos.ocorrido_em >= now() - interval '90 days'), 0) AS saidas_90_dias,
  CASE WHEN posicao.quantidade_fisica > 0 THEN
    COALESCE(sum(abs(movimentos.quantidade)) FILTER (WHERE movimentos.quantidade < 0 AND movimentos.ocorrido_em >= now() - interval '90 days'), 0) / posicao.quantidade_fisica
  ELSE 0 END AS giro_90_dias
FROM erp.vw_posicao_estoque AS posicao
LEFT JOIN erp.movimentacoes_estoque AS movimentos
  ON movimentos.tenant_id = posicao.tenant_id AND movimentos.produto_id = posicao.produto_id AND movimentos.local_estoque_id = posicao.local_estoque_id
GROUP BY posicao.tenant_id, posicao.produto_id, posicao.produto, posicao.local_estoque_id, posicao.local_estoque, posicao.quantidade_fisica;

