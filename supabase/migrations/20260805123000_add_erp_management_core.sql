CREATE OR REPLACE VIEW erp.vw_fluxo_caixa_diario
WITH (security_invoker = true)
AS
WITH movimentos AS (
  SELECT pagamentos.tenant_id, pagamentos.conta_financeira_id, pagamentos.data_pagamento AS data,
    CASE WHEN pagamentos.tipo = 'receber' THEN pagamentos.valor_liquido ELSE 0 END AS entradas,
    CASE WHEN pagamentos.tipo = 'pagar' THEN pagamentos.valor_liquido ELSE 0 END AS saidas
  FROM erp.pagamentos
  WHERE pagamentos.excluido_em IS NULL AND pagamentos.estornado_em IS NULL AND pagamentos.estorno_de_pagamento_id IS NULL
  UNION ALL
  SELECT transferencias.tenant_id, transferencias.conta_destino_id, transferencias.data_transferencia, transferencias.valor, 0
  FROM erp.transferencias_financeiras AS transferencias
  WHERE transferencias.excluido_em IS NULL AND transferencias.status = 'concluida'
  UNION ALL
  SELECT transferencias.tenant_id, transferencias.conta_origem_id, transferencias.data_transferencia, 0, transferencias.valor
  FROM erp.transferencias_financeiras AS transferencias
  WHERE transferencias.excluido_em IS NULL AND transferencias.status = 'concluida'
)
SELECT tenant_id, conta_financeira_id, data,
  sum(entradas)::numeric(18,2) AS entradas,
  sum(saidas)::numeric(18,2) AS saidas,
  (sum(entradas) - sum(saidas))::numeric(18,2) AS saldo_dia
FROM movimentos
GROUP BY tenant_id, conta_financeira_id, data;

CREATE OR REPLACE VIEW erp.vw_dre_gerencial
WITH (security_invoker = true)
AS
SELECT contas.tenant_id,
  date_trunc('month', COALESCE(contas.data_competencia, contas.data_emissao))::date AS competencia,
  categorias.id AS categoria_id,
  categorias.nome AS categoria,
  'receita'::text AS tipo,
  sum(contas.valor_total)::numeric(18,2) AS valor
FROM erp.contas_receber AS contas
LEFT JOIN erp.categorias AS categorias ON categorias.tenant_id = contas.tenant_id AND categorias.id = contas.categoria_id
WHERE contas.excluido_em IS NULL AND contas.status <> 'cancelado'
GROUP BY contas.tenant_id, date_trunc('month', COALESCE(contas.data_competencia, contas.data_emissao))::date, categorias.id, categorias.nome
UNION ALL
SELECT contas.tenant_id,
  date_trunc('month', COALESCE(contas.data_competencia, contas.data_emissao))::date,
  categorias.id, categorias.nome, 'despesa'::text,
  (sum(contas.valor_total) * -1)::numeric(18,2)
FROM erp.contas_pagar AS contas
LEFT JOIN erp.categorias AS categorias ON categorias.tenant_id = contas.tenant_id AND categorias.id = contas.categoria_id
WHERE contas.excluido_em IS NULL AND contas.status <> 'cancelado'
GROUP BY contas.tenant_id, date_trunc('month', COALESCE(contas.data_competencia, contas.data_emissao))::date, categorias.id, categorias.nome;

CREATE OR REPLACE VIEW erp.vw_aging_receber
WITH (security_invoker = true)
AS
SELECT parcelas.tenant_id, contas.cliente_id, entidades.nome AS cliente,
  parcelas.id AS parcela_id, contas.id AS conta_id, parcelas.data_vencimento,
  greatest(parcelas.valor - parcelas.valor_pago, 0)::numeric(18,2) AS saldo,
  greatest(CURRENT_DATE - parcelas.data_vencimento, 0) AS dias_atraso,
  CASE WHEN parcelas.data_vencimento >= CURRENT_DATE THEN 'a_vencer'
    WHEN CURRENT_DATE - parcelas.data_vencimento <= 30 THEN '1_30'
    WHEN CURRENT_DATE - parcelas.data_vencimento <= 60 THEN '31_60'
    WHEN CURRENT_DATE - parcelas.data_vencimento <= 90 THEN '61_90' ELSE 'mais_90' END AS faixa
FROM erp.contas_receber_parcelas AS parcelas
JOIN erp.contas_receber AS contas ON contas.tenant_id = parcelas.tenant_id AND contas.id = parcelas.conta_receber_id
JOIN erp.entidades ON entidades.tenant_id = contas.tenant_id AND entidades.id = contas.cliente_id
WHERE parcelas.excluido_em IS NULL AND parcelas.status IN ('aberto', 'parcial', 'vencido');

