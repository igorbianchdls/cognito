    SELECT 1 FROM pg_constraint
    WHERE conname = 'compras_impostos_adicionais_chk'
      AND conrelid = 'erp.compras'::regclass
  ) THEN
    ALTER TABLE erp.compras
      ADD CONSTRAINT compras_impostos_adicionais_chk CHECK (impostos_adicionais >= 0);
  END IF;
END $$;

