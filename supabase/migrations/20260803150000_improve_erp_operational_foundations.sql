  FOREACH tabela IN ARRAY ARRAY['entidades', 'categorias', 'produtos', 'servicos', 'contas_financeiras', 'notas_fiscais']
  LOOP
    IF NOT EXISTS (
      SELECT 1
      FROM pg_constraint
      WHERE conname = tabela || '_versao_chk'
        AND conrelid = format('erp.%I', tabela)::regclass
    ) THEN
      EXECUTE format(
        'ALTER TABLE erp.%I ADD CONSTRAINT %I CHECK (versao > 0)',
        tabela,
        tabela || '_versao_chk'
      );
    END IF;
  END LOOP;

