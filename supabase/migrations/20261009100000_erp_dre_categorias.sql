  FOR EACH ROW EXECUTE FUNCTION erp.herdar_classificacao_categoria();
CREATE TRIGGER repassar_classificacao AFTER UPDATE OF dre_grupo_id, fora_dre ON erp.categorias
  FOR EACH ROW WHEN (NEW.categoria_pai_id IS NULL) EXECUTE FUNCTION erp.repassar_classificacao_categoria();
