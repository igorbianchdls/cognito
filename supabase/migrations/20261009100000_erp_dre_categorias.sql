CREATE OR REPLACE FUNCTION erp.efetivacao_receber()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'pg_catalog' AS $$
BEGIN
  PERFORM erp.travar_evolucao(NEW.empresa_id);
  IF TG_OP = 'UPDATE' AND OLD.tipo_lancamento = 'previsao' AND NEW.tipo_lancamento = 'efetivo' THEN NEW.efetivado_em := now(); END IF;
  IF NEW.tipo_lancamento = 'previsao' AND (NEW.efetivado_em IS NOT NULL OR NEW.venda_id IS NOT NULL OR EXISTS (
    SELECT 1 FROM erp.contas_receber_parcelas p WHERE p.empresa_id = NEW.empresa_id AND p.conta_receber_id = NEW.id AND (
      EXISTS (SELECT 1 FROM erp.pagamentos m WHERE m.empresa_id = p.empresa_id AND m.conta_receber_parcela_id = p.id)
      OR EXISTS (SELECT 1 FROM erp.adiantamentos_aplicacoes a WHERE a.empresa_id = p.empresa_id AND a.conta_receber_parcela_id = p.id)
      OR EXISTS (SELECT 1 FROM erp.renegociacoes_parcelas r WHERE r.empresa_id = p.empresa_id AND r.conta_receber_parcela_id = p.id)))) THEN
    RAISE EXCEPTION 'Receita efetivada, vinda de venda ou já utilizada não pode ser previsão' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION erp.efetivacao_receber() FROM PUBLIC;
CREATE TRIGGER efetivacao_receber BEFORE INSERT OR UPDATE ON erp.contas_receber FOR EACH ROW EXECUTE FUNCTION erp.efetivacao_receber();

-- Baixa, adiantamento e renegociação exigem título efetivo dos dois lados.
CREATE OR REPLACE FUNCTION erp.exigir_obrigacao_efetiva()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'pg_catalog' AS $$
DECLARE linha jsonb := to_jsonb(NEW); parcela bigint; tipo text;
BEGIN
  parcela := (linha ->> 'conta_pagar_parcela_id')::bigint;
  IF parcela IS NOT NULL THEN
    SELECT t.tipo_lancamento INTO tipo FROM erp.contas_pagar_parcelas p JOIN erp.contas_pagar t ON t.empresa_id = p.empresa_id AND t.id = p.conta_pagar_id
    WHERE p.empresa_id = NEW.empresa_id AND p.id = parcela;
    IF tipo = 'previsao' THEN RAISE EXCEPTION 'Efetive a previsao antes de liquidar na mesma transacao' USING ERRCODE = '23514'; END IF;
  END IF;
  parcela := (linha ->> 'conta_receber_parcela_id')::bigint;
  IF parcela IS NOT NULL THEN
    SELECT t.tipo_lancamento INTO tipo FROM erp.contas_receber_parcelas p JOIN erp.contas_receber t ON t.empresa_id = p.empresa_id AND t.id = p.conta_receber_id
    WHERE p.empresa_id = NEW.empresa_id AND p.id = parcela;
    IF tipo = 'previsao' THEN RAISE EXCEPTION 'Efetive a receita prevista antes de receber' USING ERRCODE = '23514'; END IF;
  END IF;
  RETURN NEW;
END $$;

