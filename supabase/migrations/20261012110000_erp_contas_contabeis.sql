CREATE TABLE erp.contas_contabeis (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id bigint NOT NULL REFERENCES shared.empresas(id) ON DELETE RESTRICT,
 codigo text NOT NULL CHECK (length(codigo) BETWEEN 1 AND 60 AND codigo ~ '^[0-9]+(\.[0-9]+)*$'),
 nome text NOT NULL CHECK (length(btrim(nome)) BETWEEN 1 AND 180),
 descricao text,
 conta_pai_id bigint,
 tipo text NOT NULL CHECK (tipo IN ('sintetica','analitica')),
 classificacao text NOT NULL CHECK (classificacao IN ('ativo','passivo','patrimonio_liquido','receita','custo','despesa')),
 natureza text NOT NULL CHECK (natureza IN ('devedora','credora')),
 ativo boolean NOT NULL DEFAULT true,
 versao integer NOT NULL DEFAULT 1 CHECK (versao > 0),
 criado_em timestamptz NOT NULL DEFAULT now(), atualizado_em timestamptz NOT NULL DEFAULT now(),
 excluido_em timestamptz,
 criado_por bigint REFERENCES shared.usuarios(id) ON DELETE SET NULL,
 atualizado_por bigint REFERENCES shared.usuarios(id) ON DELETE SET NULL,
 UNIQUE (empresa_id,id), UNIQUE (empresa_id,codigo),
 FOREIGN KEY (empresa_id,conta_pai_id) REFERENCES erp.contas_contabeis(empresa_id,id) ON DELETE RESTRICT,
 CHECK (conta_pai_id IS DISTINCT FROM id), CHECK (excluido_em IS NULL)
);
CREATE INDEX contas_contabeis_pai_idx ON erp.contas_contabeis(empresa_id,conta_pai_id);
CREATE INDEX contas_contabeis_selecao_idx ON erp.contas_contabeis(empresa_id,classificacao,codigo) WHERE ativo AND tipo='analitica';
SELECT erp.criar_politicas_padrao('contas_contabeis','referencias','erp.cadastros.gerenciar');
GRANT USAGE,SELECT ON SEQUENCE erp.contas_contabeis_id_seq TO erp_runtime;

ALTER TABLE erp.categorias ADD COLUMN conta_contabil_id bigint;
ALTER TABLE erp.contas_financeiras ADD COLUMN conta_contabil_id bigint;
ALTER TABLE erp.categorias ADD CONSTRAINT categorias_conta_contabil_fk FOREIGN KEY (empresa_id,conta_contabil_id) REFERENCES erp.contas_contabeis(empresa_id,id) ON DELETE RESTRICT;
ALTER TABLE erp.contas_financeiras ADD CONSTRAINT contas_financeiras_conta_contabil_fk FOREIGN KEY (empresa_id,conta_contabil_id) REFERENCES erp.contas_contabeis(empresa_id,id) ON DELETE RESTRICT;
CREATE INDEX categorias_conta_contabil_idx ON erp.categorias(empresa_id,conta_contabil_id) WHERE conta_contabil_id IS NOT NULL;
CREATE INDEX contas_financeiras_conta_contabil_idx ON erp.contas_financeiras(empresa_id,conta_contabil_id) WHERE conta_contabil_id IS NOT NULL;
ALTER TABLE erp.cadastros_eventos DROP CONSTRAINT cadastros_eventos_tipo_chk;
ALTER TABLE erp.cadastros_eventos ADD CONSTRAINT cadastros_eventos_tipo_chk CHECK (entidade_tipo IN ('entidade','categoria','categoria_cadastro','produto','servico','conta_financeira','conta_contabil'));

-- Serialize graph edits and new bindings in the same company, including direct SQL.
CREATE FUNCTION erp.validar_conta_contabil() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE pai record; vinculado boolean;
BEGIN
 PERFORM pg_advisory_xact_lock(hashtextextended('erp:contabilidade:'||(CASE WHEN TG_OP='DELETE' THEN OLD.empresa_id ELSE NEW.empresa_id END)::text,0));
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Desative a conta contábil para preservar o histórico' USING ERRCODE='23514'; END IF;
 IF TG_OP='UPDATE' THEN
  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.empresa_id IS DISTINCT FROM OLD.empresa_id THEN
   RAISE EXCEPTION 'A empresa e a identificação da conta são imutáveis' USING ERRCODE='23514';
  END IF;
  IF NEW.versao <> OLD.versao+1 THEN RAISE EXCEPTION 'CONFLITO_VERSAO: incremente a versão da conta contábil' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.conta_pai_id IS NOT NULL THEN
  SELECT tipo,classificacao,ativo INTO pai FROM erp.contas_contabeis WHERE empresa_id=NEW.empresa_id AND id=NEW.conta_pai_id;
  IF NOT FOUND OR pai.tipo <> 'sintetica' OR pai.classificacao <> NEW.classificacao THEN
   RAISE EXCEPTION 'A conta superior deve ser sintética, da mesma empresa e classificação' USING ERRCODE='23514';
  END IF;
  IF EXISTS(WITH RECURSIVE ancestrais AS (
   SELECT id,conta_pai_id,ativo,ARRAY[id] caminho FROM erp.contas_contabeis WHERE empresa_id=NEW.empresa_id AND id=NEW.conta_pai_id
   UNION ALL SELECT c.id,c.conta_pai_id,c.ativo,a.caminho||c.id FROM erp.contas_contabeis c JOIN ancestrais a ON c.empresa_id=NEW.empresa_id AND c.id=a.conta_pai_id WHERE NOT c.id=ANY(a.caminho)
  ) SELECT 1 FROM ancestrais WHERE id=NEW.id OR (NEW.ativo AND NOT ativo)) THEN
   RAISE EXCEPTION 'Hierarquia circular ou conta superior inativa' USING ERRCODE='23514';
  END IF;
 END IF;
 IF EXISTS(SELECT 1 FROM erp.contas_contabeis c WHERE c.empresa_id=NEW.empresa_id AND c.conta_pai_id=NEW.id
    AND (NEW.tipo <> 'sintetica' OR c.classificacao <> NEW.classificacao OR (NOT NEW.ativo AND c.ativo))) THEN
  RAISE EXCEPTION 'A alteração é incompatível com as contas filhas; revise-as primeiro' USING ERRCODE='23514';
 END IF;
 SELECT EXISTS(SELECT 1 FROM erp.categorias WHERE empresa_id=NEW.empresa_id AND conta_contabil_id=NEW.id)
     OR EXISTS(SELECT 1 FROM erp.contas_financeiras WHERE empresa_id=NEW.empresa_id AND conta_contabil_id=NEW.id) INTO vinculado;
 IF vinculado AND (NEW.tipo <> 'analitica' OR (TG_OP='UPDATE' AND (NEW.codigo IS DISTINCT FROM OLD.codigo OR NEW.classificacao IS DISTINCT FROM OLD.classificacao OR NEW.natureza IS DISTINCT FROM OLD.natureza))) THEN
  RAISE EXCEPTION 'Conta vinculada: preserve código, classificação, natureza e tipo analítico' USING ERRCODE='23514';
 END IF;
 IF NOT NEW.ativo AND (EXISTS(SELECT 1 FROM erp.categorias WHERE empresa_id=NEW.empresa_id AND conta_contabil_id=NEW.id AND ativo AND excluido_em IS NULL)
   OR EXISTS(SELECT 1 FROM erp.contas_financeiras WHERE empresa_id=NEW.empresa_id AND conta_contabil_id=NEW.id AND ativo AND excluido_em IS NULL)) THEN
  RAISE EXCEPTION 'Desvincule os cadastros ativos antes de desativar esta conta contábil' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION erp.validar_conta_contabil() FROM PUBLIC,anon,authenticated,erp_runtime;
CREATE TRIGGER validar_conta_contabil BEFORE INSERT OR UPDATE OR DELETE ON erp.contas_contabeis FOR EACH ROW EXECUTE FUNCTION erp.validar_conta_contabil();

CREATE FUNCTION erp.validar_vinculo_contabil() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
BEGIN
 IF NEW.conta_contabil_id IS NULL THEN RETURN NEW; END IF;
 IF TG_OP='UPDATE' AND NEW.empresa_id IS NOT DISTINCT FROM OLD.empresa_id AND NEW.conta_contabil_id IS NOT DISTINCT FROM OLD.conta_contabil_id AND NOT (NEW.ativo AND NOT OLD.ativo) THEN RETURN NEW; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('erp:contabilidade:'||NEW.empresa_id::text,0));
 IF NOT EXISTS(SELECT 1 FROM erp.contas_contabeis WHERE empresa_id=NEW.empresa_id AND id=NEW.conta_contabil_id AND tipo='analitica' AND ativo AND excluido_em IS NULL) THEN
  RAISE EXCEPTION 'Selecione uma conta contábil analítica ativa da mesma empresa' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION erp.validar_vinculo_contabil() FROM PUBLIC,anon,authenticated,erp_runtime;
CREATE TRIGGER validar_vinculo_contabil BEFORE INSERT OR UPDATE ON erp.categorias FOR EACH ROW EXECUTE FUNCTION erp.validar_vinculo_contabil();
CREATE TRIGGER validar_vinculo_contabil BEFORE INSERT OR UPDATE ON erp.contas_financeiras FOR EACH ROW EXECUTE FUNCTION erp.validar_vinculo_contabil();
COMMENT ON TABLE erp.contas_contabeis IS 'Plano de contas por empresa; grupos sintéticos e contas analíticas na mesma hierarquia. Não registra partidas contábeis.';
COMMIT;
