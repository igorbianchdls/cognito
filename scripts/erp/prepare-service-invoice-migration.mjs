import {readFileSync,writeFileSync} from 'node:fs'
const previous=readFileSync('supabase/migrations/20261006010000_prepare_erp_fiscal_integration.sql','utf8')
const start=previous.indexOf('CREATE FUNCTION erp.validar_integridade_nota_fiscal()')
const end=previous.indexOf('CREATE TRIGGER validar_integridade_nota',start)
let guard=previous.slice(start,end).replace('CREATE FUNCTION','CREATE OR REPLACE FUNCTION')
guard=guard.replaceAll("ARRAY['status'","ARRAY['modo_operacao','status'")
guard=guard.replace("  IF NEW.direcao='saida' AND NEW.status IN", "  IF NEW.provedor IS DISTINCT FROM 'simulador_local' AND NEW.direcao='saida' AND NEW.status IN")
guard=guard.replace("  IF TG_OP='DELETE' THEN",`  IF TG_OP='UPDATE' AND OLD.provedor='simulador_local' AND NEW.provedor IS DISTINCT FROM OLD.provedor THEN
    RAISE EXCEPTION 'Uma nota simulada não pode ser convertida em nota real' USING ERRCODE='23514';
  END IF;
  IF TG_OP='DELETE' THEN`)
const sql=`BEGIN;

-- Generated mode classifies existing demonstrations without rewriting frozen invoice data.
ALTER TABLE erp.notas_fiscais ADD COLUMN modo_operacao text GENERATED ALWAYS AS
 (CASE WHEN provedor='simulador_local' THEN 'simulacao' ELSE 'real' END) STORED,
 ADD COLUMN simulacao_cenario text NOT NULL DEFAULT 'sucesso'
 CHECK(simulacao_cenario IN ('sucesso','rejeicao','demora','timeout'));
ALTER TABLE erp.notas_fiscais ADD CONSTRAINT notas_fiscais_simulacao_chk CHECK(
 modo_operacao<>'simulacao' OR (ambiente='homologacao' AND numero LIKE 'DEMO-%'
 AND chave_acesso IS NULL AND token_placeholder_check(metadata)));

${guard}
ALTER TABLE erp.notas_fiscais_tentativas DROP CONSTRAINT notas_fiscais_tentativas_acao_check;
ALTER TABLE erp.notas_fiscais_tentativas ADD CONSTRAINT notas_fiscais_tentativas_acao_check
 CHECK(acao IN ('criar','editar','excluir','emitir','consultar','cancelar','corrigir','substituir','inutilizar'));

CREATE TABLE erp.notas_fiscais_pdfs(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id bigint NOT NULL REFERENCES shared.empresas(id) ON DELETE RESTRICT,
 nota_fiscal_id bigint NOT NULL,versao integer NOT NULL CHECK(versao>0),
 conteudo bytea NOT NULL CHECK(octet_length(conteudo) BETWEEN 100 AND 2097152),
 hash_sha256 text NOT NULL CHECK(hash_sha256 ~ '^[0-9a-f]{64}$'),
 nome text NOT NULL CHECK(nome ~ '^DEMO-[a-zA-Z0-9-]+\\.pdf$'),
 criado_em timestamptz NOT NULL DEFAULT now(),criado_por bigint REFERENCES shared.usuarios(id),
 UNIQUE(empresa_id,id),UNIQUE(empresa_id,nota_fiscal_id,versao),
 FOREIGN KEY(empresa_id,nota_fiscal_id) REFERENCES erp.notas_fiscais(empresa_id,id) ON DELETE RESTRICT
);
ALTER TABLE erp.notas_fiscais_pdfs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON erp.notas_fiscais_pdfs FROM PUBLIC,anon,authenticated,erp_runtime;
GRANT SELECT,INSERT ON erp.notas_fiscais_pdfs TO erp_runtime,service_role;
GRANT USAGE,SELECT ON SEQUENCE erp.notas_fiscais_pdfs_id_seq TO erp_runtime,service_role;
CREATE POLICY ler_pdf_fiscal ON erp.notas_fiscais_pdfs FOR SELECT TO erp_runtime USING(
 EXISTS(SELECT 1 FROM erp.notas_fiscais n WHERE n.empresa_id=notas_fiscais_pdfs.empresa_id
 AND n.id=notas_fiscais_pdfs.nota_fiscal_id AND n.excluido_em IS NULL));
CREATE POLICY inserir_pdf_fiscal ON erp.notas_fiscais_pdfs FOR INSERT TO erp_runtime WITH CHECK(
 shared.has_erp_capability(empresa_id,'erp.vendas.gerenciar') AND EXISTS(
 SELECT 1 FROM erp.notas_fiscais n WHERE n.empresa_id=notas_fiscais_pdfs.empresa_id
 AND n.id=notas_fiscais_pdfs.nota_fiscal_id AND n.modo_operacao='simulacao' AND n.tipo='nfse'));
CREATE TRIGGER pdf_fiscal_imutavel BEFORE UPDATE OR DELETE ON erp.notas_fiscais_pdfs
 FOR EACH ROW EXECUTE FUNCTION erp.bloquear_mutacao_evento();
COMMENT ON TABLE erp.notas_fiscais_pdfs IS 'PDFs demonstrativos privados e versionados, servidos somente pela API autenticada. Sem transmissão fiscal externa.';
COMMIT;
`.replace('token_placeholder_check(metadata)',"metadata @> '{\"simulado\":true,\"sem_validade_fiscal\":true}'::jsonb")
writeFileSync('supabase/migrations/20261006020000_service_invoice_simulation.sql',sql)
