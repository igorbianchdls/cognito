CREATE TRIGGER evento_acordo AFTER UPDATE OF status ON erp.renegociacoes FOR EACH ROW WHEN(OLD.status IS DISTINCT FROM NEW.status) EXECUTE FUNCTION erp.evento_credito_acordo();

DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['adiantamentos','adiantamentos_aplicacoes','renegociacoes','renegociacoes_parcelas','pagamentos'] LOOP
 EXECUTE format('CREATE TRIGGER a_validar_movimento_evolucao BEFORE INSERT OR UPDATE OR DELETE ON erp.%I FOR EACH ROW EXECUTE FUNCTION erp.validar_movimento_evolucao()',t);
 END LOOP;
 FOREACH t IN ARRAY ARRAY['contas_receber','contas_pagar','contas_receber_parcelas','contas_pagar_parcelas','conciliacoes_bancarias_itens','conciliacoes_bancarias','transacoes_bancarias','transferencias_financeiras'] LOOP
 EXECUTE format('CREATE TRIGGER a_proteger_dependencias BEFORE INSERT OR UPDATE OR DELETE ON erp.%I FOR EACH ROW EXECUTE FUNCTION erp.proteger_dependencias_financeiras()',t);
 END LOOP;
 FOREACH t IN ARRAY ARRAY['adiantamentos','adiantamentos_aplicacoes','renegociacoes','renegociacoes_parcelas','pagamentos','contas_receber','contas_pagar','contas_receber_parcelas','contas_pagar_parcelas'] LOOP
 EXECUTE format('CREATE CONSTRAINT TRIGGER validar_saldos AFTER INSERT OR UPDATE OR DELETE ON erp.%I DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION erp.validar_saldos_evolucao()',t);
 END LOOP;
 FOREACH t IN ARRAY ARRAY['adiantamentos','pagamentos','conciliacoes_bancarias_itens','conciliacoes_bancarias','transacoes_bancarias','transferencias_financeiras'] LOOP
 EXECUTE format('CREATE CONSTRAINT TRIGGER validar_conciliacao AFTER INSERT OR UPDATE OR DELETE ON erp.%I DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION erp.validar_conciliacao_evolucao()',t);
 END LOOP;
END $$;

